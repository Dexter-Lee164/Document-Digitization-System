"""Microsoft Word (.docx) generation with python-docx.

Guarantees (verified by tests): A4 page, 2.54 cm margins, every run and the document defaults are
Times New Roman 12 pt, all text is real editable text (never an embedded picture).
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Iterable

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt

from processing.common import ParameterError

FONT_NAME = "Times New Roman"
FONT_SIZE_PT = 12
_CONTROL_CHARS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f￾￿]")


def sanitize(text: str | None) -> str:
    """Remove characters that are illegal in XML 1.0 (they would make Word report a corrupt file) and unify newlines."""
    if text is None:
        return ""
    text = str(text).replace("\r\n", "\n").replace("\r", "\n")
    return _CONTROL_CHARS.sub("", text)


def _force_font(rpr_parent) -> None:
    """Write explicit Times New Roman 12 pt into an rPr container, removing theme font overrides."""
    rpr = rpr_parent.get_or_add_rPr() if hasattr(rpr_parent, "get_or_add_rPr") else rpr_parent
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.insert(0, rfonts)
    for attr in ("w:asciiTheme", "w:hAnsiTheme", "w:eastAsiaTheme", "w:cstheme"):
        if rfonts.get(qn(attr)) is not None:
            del rfonts.attrib[qn(attr)]
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        rfonts.set(qn(attr), FONT_NAME)
    for tag in ("w:sz", "w:szCs"):
        el = rpr.find(qn(tag))
        if el is None:
            el = OxmlElement(tag)
            rpr.append(el)
        el.set(qn("w:val"), str(FONT_SIZE_PT * 2))


def _new_document(title: str | None) -> Document:
    doc = Document()
    section = doc.sections[0]
    section.page_width, section.page_height = Cm(21.0), Cm(29.7)  # A4
    section.left_margin = section.right_margin = section.top_margin = section.bottom_margin = Cm(2.54)

    # document defaults (so text the user types later is also Times New Roman 12)
    styles_el = doc.styles.element
    defaults = styles_el.find(qn("w:docDefaults"))
    if defaults is not None:
        rpr_default = defaults.find(qn("w:rPrDefault"))
        if rpr_default is not None:
            rpr = rpr_default.find(qn("w:rPr"))
            if rpr is not None:
                _force_font(rpr)

    normal = doc.styles["Normal"]
    normal.font.name = FONT_NAME
    normal.font.size = Pt(FONT_SIZE_PT)
    _force_font(normal.element.get_or_add_rPr())
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.15

    props = doc.core_properties
    props.author = "DocuVision"
    props.title = sanitize(title) or "Digitized document"
    props.comments = "Generated by DocuVision from recognised and user-corrected text."
    return doc


def _add_text_run(paragraph, text: str, bold: bool = False):
    """Add text to ``paragraph``; embedded newlines become Word line breaks."""
    lines = sanitize(text).split("\n")
    run = None
    for i, line in enumerate(lines):
        run = paragraph.add_run()
        if i > 0:
            run.add_break()
        run.add_text(line)
        run.font.name = FONT_NAME
        run.font.size = Pt(FONT_SIZE_PT)
        run.bold = bold
        _force_font(run._element)
    if run is None:  # empty string still needs one formatted run so the paragraph keeps the font
        run = paragraph.add_run("")
        run.font.name = FONT_NAME
        run.font.size = Pt(FONT_SIZE_PT)
        _force_font(run._element)
    return run


def split_paragraphs(text: str, reflow: bool = True) -> list[str]:
    """Split on blank lines. With ``reflow`` the hard line wraps inside a paragraph are joined with spaces."""
    text = sanitize(text).strip("\n")
    if not text.strip():
        return []
    blocks = re.split(r"\n[ \t]*\n+", text)
    out: list[str] = []
    for block in blocks:
        lines = [ln.rstrip() for ln in block.split("\n")]
        if reflow:
            out.append(" ".join(ln.strip() for ln in lines if ln.strip()))
        else:
            out.append("\n".join(lines).strip("\n"))
    return [p for p in out if p.strip()]


def _add_paragraphs(doc, text: str, reflow: bool) -> int:
    count = 0
    for para in split_paragraphs(text, reflow):
        _add_text_run(doc.add_paragraph(), para)
        count += 1
    return count


def _set_cell_text(cell, text: str, bold: bool = False) -> None:
    paragraph = cell.paragraphs[0]
    _add_text_run(paragraph, text, bold)


def build_text_document(output_path: Path, text: str, reflow: bool = True, title: str | None = None) -> dict:
    doc = _new_document(title)
    if title and title.strip():
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _add_text_run(p, title.strip(), bold=True)
    count = _add_paragraphs(doc, text, reflow)
    if count == 0 and not (title and title.strip()):
        # A completely empty Word file is confusing; keep one empty formatted paragraph.
        _add_text_run(doc.add_paragraph(), "")
    doc.save(str(output_path))
    return {"paragraphs": count, "table_rows": 0}


def build_form_document(
    output_path: Path,
    title: str,
    fields: Iterable[dict],
    full_text: str = "",
    include_full_text: bool = True,
    reflow: bool = True,
) -> dict:
    fields = list(fields)
    if not fields:
        raise ParameterError("A structured form export needs at least one field.")
    doc = _new_document(title)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _add_text_run(p, (title or "FORM").upper(), bold=True)

    table = doc.add_table(rows=1, cols=2)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    header = table.rows[0].cells
    _set_cell_text(header[0], "Field", bold=True)
    _set_cell_text(header[1], "Value", bold=True)
    for field in fields:
        row = table.add_row().cells
        _set_cell_text(row[0], str(field.get("label") or field.get("key") or ""), bold=True)
        _set_cell_text(row[1], str(field.get("value") or ""))
    for row in table.rows:
        row.cells[0].width = Cm(5.2)
        row.cells[1].width = Cm(10.8)

    paragraphs = 0
    if include_full_text and full_text.strip():
        doc.add_paragraph()
        _add_text_run(doc.add_paragraph(), "Other recognized text", bold=True)
        paragraphs = _add_paragraphs(doc, full_text, reflow)
    doc.save(str(output_path))
    return {"paragraphs": paragraphs, "table_rows": len(fields) + 1}


def verify_docx(path: Path) -> dict:
    """Re-open the generated file and report its properties (raises if python-docx cannot read it)."""
    doc = Document(str(path))
    runs = [r for p in doc.paragraphs for r in p.runs]
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for p in cell.paragraphs:
                    runs.extend(p.runs)
    fonts_ok = all((r.font.name == FONT_NAME and r.font.size == Pt(FONT_SIZE_PT)) for r in runs)
    section = doc.sections[0]
    return {
        "runs": len(runs),
        "font_ok": fonts_ok,
        "a4": abs(section.page_width.cm - 21.0) < 0.05 and abs(section.page_height.cm - 29.7) < 0.05,
        "tables": len(doc.tables),
        "paragraphs": len(doc.paragraphs),
    }

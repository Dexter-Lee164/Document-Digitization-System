'use strict';
const fs = require('node:fs');
const fsp = require('node:fs/promises');
const path = require('node:path');
const { badRequest } = require('./errors');

// Same allow-list as the Python service (api/storage.py): <area>/<segment>[/<segment>...].<ext>
const SEGMENT = '[A-Za-z0-9][A-Za-z0-9_\\-]{0,63}';
const KEY_RE = new RegExp(`^(uploads|processed|exports)/${SEGMENT}(/${SEGMENT})*\\.(png|jpg|jpeg|docx)$`);
const PREFIX_RE = new RegExp(`^processed/${SEGMENT}$`);

const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.docx': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' };

/**
 * Private file storage shared with the CV service. Keys are generated by the server - never taken from the browser -
 * and are still validated + resolved inside the storage root before any file system call.
 */
class Storage {
  constructor(root) {
    this.root = path.resolve(root);
  }

  ensure() {
    for (const sub of ['uploads', 'processed', 'exports']) fs.mkdirSync(path.join(this.root, sub), { recursive: true });
    return this;
  }

  abs(key) {
    if (typeof key !== 'string' || !KEY_RE.test(key)) throw badRequest('Invalid storage key.', undefined, 'invalid_storage_key');
    const full = path.resolve(this.root, key);
    if (full !== this.root && !full.startsWith(this.root + path.sep)) throw badRequest('Invalid storage key.', undefined, 'invalid_storage_key');
    return full;
  }

  async write(key, buffer) {
    const target = this.abs(key);
    await fsp.mkdir(path.dirname(target), { recursive: true });
    await fsp.writeFile(target, buffer, { flag: 'wx', mode: 0o640 }); // wx: never overwrite an existing file
  }

  async exists(key) {
    try { await fsp.access(this.abs(key)); return true; } catch { return false; }
  }

  async remove(key) {
    if (!key) return;
    try { await fsp.unlink(this.abs(key)); } catch (err) { if (err.code !== 'ENOENT') throw err; }
  }

  /** Remove a processed/<id> directory (all derived images of one document). */
  async removeDir(prefix) {
    if (!prefix || !PREFIX_RE.test(prefix)) return;
    const dir = path.resolve(this.root, prefix);
    if (!dir.startsWith(this.root + path.sep)) return;
    await fsp.rm(dir, { recursive: true, force: true });
  }

  contentType(key) {
    return MIME[path.extname(key).toLowerCase()] || 'application/octet-stream';
  }
}

module.exports = { Storage, KEY_RE, PREFIX_RE, MIME };
